import ArabesqueSystem
import Carbon
import Foundation

/// Generates the "Arabesque Base" keyboard layout from the system ABC layout:
/// identical to ABC without ⌥, and the ⌥ layers copy the plain layers so no dead key exists.
enum BaseLayoutGenerator {
    enum Failure: Error { case abcLayoutMissing }

    /// keyMap index → Carbon modifiers sampled from ABC. Indices 3–5 are the ⌥ layers.
    static let samples: [(index: Int, modifiers: Int)] = [
        (0, 0), (1, shiftKey), (2, alphaLock),
        (3, 0), (4, shiftKey), (5, alphaLock),
        (6, cmdKey), (7, controlKey),
    ]

    static let modifierMap = """
        <modifierMap id="Modifiers" defaultIndex="0">
            <keyMapSelect mapIndex="0"><modifier keys=""/></keyMapSelect>
            <keyMapSelect mapIndex="1"><modifier keys="anyShift caps?"/></keyMapSelect>
            <keyMapSelect mapIndex="2"><modifier keys="caps"/></keyMapSelect>
            <keyMapSelect mapIndex="3"><modifier keys="anyOption"/></keyMapSelect>
            <keyMapSelect mapIndex="4"><modifier keys="anyShift caps? anyOption"/></keyMapSelect>
            <keyMapSelect mapIndex="5"><modifier keys="caps anyOption"/></keyMapSelect>
            <keyMapSelect mapIndex="6"><modifier keys="anyShift? caps? anyOption? command"/></keyMapSelect>
            <keyMapSelect mapIndex="7"><modifier keys="anyShift? caps? anyOption? command? anyControl"/></keyMapSelect>
        </modifierMap>
    """

    static func write(to url: URL) throws {
        guard let source = InputSources.source(withID: InputSources.fallbackLayoutID),
              let raw = TISGetInputSourceProperty(source, kTISPropertyUnicodeKeyLayoutData)
        else { throw Failure.abcLayoutMissing }
        let data = Unmanaged<CFData>.fromOpaque(raw).takeUnretainedValue()
        try withExtendedLifetime(data) {
            let layout = unsafeBitCast(CFDataGetBytePtr(data), to: UnsafePointer<UCKeyboardLayout>.self)
            try xml(layout: layout, keyboardType: UInt32(LMGetKbdType()))
                .write(to: url, atomically: true, encoding: .utf8)
        }
    }

    static func xml(layout: UnsafePointer<UCKeyboardLayout>, keyboardType: UInt32) -> String {
        var keyMaps = ""
        var maxOutput = 1
        for (index, modifiers) in samples {
            keyMaps += "        <keyMap index=\"\(index)\">\n"
            for code in 0..<128 {
                let output = translate(layout, UInt16(code), modifiers: modifiers, keyboardType: keyboardType)
                guard !output.isEmpty else { continue }
                maxOutput = max(maxOutput, output.utf16.count)
                keyMaps += "            <key code=\"\(code)\" output=\"\(escape(output))\"/>\n"
            }
            keyMaps += "        </keyMap>\n"
        }
        // Group 126 is Unicode: macOS accepts negative keyboard ids only there.
        return """
        <?xml version="1.1" encoding="UTF-8"?>
        <!DOCTYPE keyboard SYSTEM "file://localhost/System/Library/DTDs/KeyboardLayout.dtd">
        <!-- Generated by ArabesqueTools base-layout from com.apple.keylayout.ABC (keyboard type \(keyboardType)). -->
        <keyboard group="126" id="-23817" name="\(InputSources.baseLayoutName)" maxout="\(maxOutput)">
            <layouts>
                <layout first="0" last="255" modifiers="Modifiers" mapSet="ANSI"/>
            </layouts>
        \(modifierMap)
            <keyMapSet id="ANSI">
        \(keyMaps)    </keyMapSet>
        </keyboard>

        """
    }

    static func translate(_ layout: UnsafePointer<UCKeyboardLayout>, _ code: UInt16, modifiers: Int,
                          keyboardType: UInt32) -> String {
        var deadKeyState: UInt32 = 0
        var length = 0
        var chars = [UniChar](repeating: 0, count: 8)
        UCKeyTranslate(layout, code, UInt16(kUCKeyActionDown), UInt32((modifiers >> 8) & 0xFF), keyboardType,
                       OptionBits(kUCKeyTranslateNoDeadKeysMask), &deadKeyState, chars.count, &length, &chars)
        return String(utf16CodeUnits: chars, count: length)
    }

    /// XML-escapes an output string with numeric references only: the keylayout compiler drops outputs
    /// written as named entities (&apos; …), and control characters need XML 1.1.
    static func escape(_ string: String) -> String {
        var escaped = ""
        for scalar in string.unicodeScalars {
            if scalar.value < 0x20 || scalar.value == 0x7F || "&<>\"'".unicodeScalars.contains(scalar) {
                escaped += String(format: "&#x%04X;", scalar.value)
            } else {
                escaped.unicodeScalars.append(scalar)
            }
        }
        return escaped
    }
}
